"""Write the golden test vectors and the 1/sqrt tables for the C++ and Verilog.

    uv run python -m dsp2si.export
"""

import pathlib

import numpy as np

from dsp2si.models import RsqrtCfg, CordicCfg, cordic_gain, normalize_a, normalize_b, rsqrt_tables, stimulus, FRAC

ROOT = pathlib.Path(__file__).resolve().parents[1]


def main(n=100_000):
    cfg_a, cfg_b = RsqrtCfg(), CordicCfg()
    i, q = stimulus(n, seed=11)
    xa, ya = normalize_a(i, q, cfg_a)
    xb, yb = normalize_b(i, q, cfg_b)

    vec = ROOT / "build" / "vectors.txt"
    vec.parent.mkdir(exist_ok=True)
    np.savetxt(vec, np.stack([i, q, xa, ya, xb, yb], 1), fmt="%d",
               header="i q xa ya xb yb   (signed Q1.15; a = table-based, b = CORDIC)")

    base, slope = rsqrt_tables(cfg_a)
    assert base.max() < (1 << 18) and slope.min() >= 0 and slope.max() < (1 << 10)

    # Verilog ROM images: one hex word per line, indexed from k = 2**(A-2)
    rtl = ROOT / "rtl"
    rtl.mkdir(exist_ok=True)
    (rtl / "rsqrt_base.hex").write_text("".join(f"{v:05x}\n" for v in base))
    (rtl / "rsqrt_slope.hex").write_text("".join(f"{v:03x}\n" for v in slope))

    # HLS header with the same tables
    hls = ROOT / "hls"
    hls.mkdir(exist_ok=True)
    rows = lambda a: ",\n".join("  " + ", ".join(str(v) for v in a[j:j + 12]) for j in range(0, len(a), 12))
    (hls / "rsqrt_tables.h").write_text(
        "// Generated by dsp2si/export.py. T[k] ~ 2^16 / sqrt(k / 2^9), D[k] = T[k] - T[k+1], k = 128..511.\n"
        "#pragma once\n#include <ap_int.h>\n\n"
        f"static const int RSQRT_ADDR_BITS = {cfg_a.addr_bits};\n"
        f"static const int RSQRT_FRAC_BITS = {cfg_a.frac_bits};\n"
        f"static const int RSQRT_ENTRIES = {len(base)};\n\n"
        f"static const ap_uint<18> RSQRT_BASE[{len(base)}] = {{\n{rows(base)}\n}};\n\n"
        f"static const ap_uint<10> RSQRT_SLOPE[{len(slope)}] = {{\n{rows(slope)}\n}};\n"
    )

    # CORDIC start value 1/K in the datapath format (Q1.(15+G)), for the RTL parameter
    inv_k = int(round((1 << (FRAC + cfg_b.guard)) / cordic_gain(cfg_b.iters)))
    (rtl / "cordic_params.vh").write_text(
        f"// Generated by dsp2si/export.py\n"
        f"localparam integer ITERS = {cfg_b.iters};\n"
        f"localparam integer GUARD = {cfg_b.guard};\n"
        f"localparam integer INV_GAIN = {inv_k};  // round(2^(15+GUARD) / K)\n"
    )
    print(f"{len(i)} vectors -> {vec.relative_to(ROOT)}; {len(base)} table entries; 1/K = {inv_k}")


if __name__ == "__main__":
    main()
